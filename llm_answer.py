
import os
from openai import OpenAI


def generate_answer(question, vector_results, graph_results):
    api_key = os.getenv("OPENAI_API_KEY")
    model = os.getenv("OPENAI_MODEL", "gpt-5-nano")

    if not api_key:
        raise RuntimeError("OPENAI_API_KEY is not configured.")

    if not vector_results:
        return (
            "I couldn't find sufficiently relevant document passages "
            "to answer this question reliably.\n\n"
            "Please try a more specific question or upload a supporting "
            "document. Knowledge-graph relationships alone are not "
            "sufficient evidence for a document-grounded answer."
        )

    context_parts = []
    available_sources = []

    # Add retrieved document passages.
    for i, item in enumerate(vector_results[:3], start=1):
        source = item.get("metadata", {}).get("source", "Unknown")
        passage = item.get("text", "")[:1500]

        context_parts.append(
            f"[Document source {i}: {source}]\n{passage}"
        )
        available_sources.append(f"[Document source {i}]")

    # Add knowledge graph relationships.
    if graph_results:
        relationships = "\n".join(
            f"- {item}" for item in graph_results[:8]
        )
        context_parts.append(
            "[Knowledge graph relationships]\n" + relationships
        )

    context = "\n\n".join(context_parts)

    instructions = """
You are a professional Oracle DBA knowledge assistant.

Answer the user's question using only the supplied retrieved context.

Formatting requirements:
1. Start with a direct answer.
2. Use short paragraphs and clear Markdown headings where useful.
3. Use bullet points or numbered steps for procedures.
4. Use **bold** for important technical terms.
5. Cite supporting document passages inline using their exact labels,
   for example [Document source 1].
6. At the end, include a **Sources** section listing only the document
   sources actually cited in your answer.
7. Never invent document names, source numbers, commands, or facts.
8. Do not claim that a statement came from a document unless that
   document's retrieved passage supports it.
9. Treat starter_knowledge graph relationships as illustrative,
   not as facts established by uploaded documents.
10. If the retrieved context is insufficient, clearly state what is
    missing instead of guessing.
11. Keep the answer concise but useful for a database administrator.
"""

    client = OpenAI(
        api_key=api_key,
        timeout=60.0,
        max_retries=1,
    )

    response = client.responses.create(
        model=model,
        reasoning={"effort": "low"},
        instructions=instructions,
        input=(
            f"Retrieved context:\n{context}\n\n"
            f"Question:\n{question}\n\n"
            "Answer using readable Markdown and accurate source citations."
        ),
        max_output_tokens=2000,
    )

    answer = response.output_text.strip()

    if response.status != "completed":
        reason = getattr(response.incomplete_details, "reason", None)
        raise RuntimeError(
            f"OpenAI response status: {response.status}; "
            f"reason: {reason or 'not provided'}"
        )

    if not answer:
        raise RuntimeError(
            "The model completed the request but returned no text."
        )

# Build the Sources section from retrieved documents.
    import re

    # Remove any model-generated Sources heading and content.
    answer = re.sub(
        r"(?ims)\n*#{0,3}\s*Sources\s*:?\s*\n.*$",
        "",
        answer,
    ).rstrip()

    # Remove standalone source filename bullets generated by the model.
    answer = re.sub(
        r"(?im)^\s*[-*]?\s*Document source\s+\d+\s*:.*$",
        "",
        answer,
    ).rstrip()

    source_lines = []
    seen_sources = set()

    for i, item in enumerate(vector_results[:3], start=1):
        source = item.get("metadata", {}).get("source", "Unknown")

        if source not in seen_sources:
            source_lines.append(
                f"- **{source}** — Retrieved document, source {i}"
            )
            seen_sources.add(source)

    if source_lines:
        answer += "\n\n### Sources\n" + "\n".join(source_lines)

    return answer
